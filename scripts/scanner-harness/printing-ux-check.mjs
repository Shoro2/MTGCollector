// Exercise printing selection on the real /scan page and synthetic four-card spread.
// Run the full-catalogue server with DISABLE_PRICE_UPDATES=1, then:
// HARNESS_URL=http://localhost:5173 node printing-ux-check.mjs fixtures/synth-grid.jpg
// Authentication is a browser hydration fixture; collection writes are intercepted.
// No users, sessions or collection rows are written to the database.
import { chromium } from 'playwright';
import { resolve } from 'node:path';

const photo = process.argv[2];
if (!photo) throw new Error('Pass the synth-grid.jpg fixture generated by make-synthetic.mjs');
const url = process.env.HARNESS_URL ?? 'http://localhost:5173';
const browser = await chromium.launch({ executablePath: process.env.PLAYWRIGHT_CHROMIUM_PATH || undefined });
let assertions = 0;
const assert = (ok, message) => { if (!ok) throw new Error(message); assertions++; console.log('ok  ' + message); };
try {
	for (const loggedIn of [false, true]) {
		const context = await browser.newContext({ viewport: { width: 390, height: 844 }, hasTouch: true, isMobile: true });
		const page = await context.newPage();
		const writes = [], errors = [];
		page.on('pageerror', (e) => errors.push(e.message));
		await page.addInitScript(() => {
			window.copiedScanText = '';
			Object.defineProperty(navigator, 'clipboard', { value: { writeText: async (text) => { window.copiedScanText = text; } } });
		});
		if (loggedIn) await page.route('**/scan', async (route) => {
			if (route.request().method() !== 'GET') return route.continue();
			const response = await route.fetch();
			const html = await response.text();
			if (!html.includes('data:{user:null}')) throw new Error('Hydration fixture no longer matches the page');
			await route.fulfill({ response, body: html.replaceAll('data:{user:null}', 'data:{user:{id:"scanner-ux",name:"Scanner check",email:"scanner@example.invalid"}}') });
		});
		await page.route('**/collection', async (route) => {
			if (route.request().method() !== 'POST') return route.continue();
			writes.push(route.request().postDataJSON());
			await route.fulfill({ status: 200, contentType: 'application/json', body: JSON.stringify({ success: true }) });
		});
		await page.goto(url + '/scan', { waitUntil: 'networkidle' });
		await page.getByRole('button', { name: 'Multiple cards', exact: true }).click();
		await page.setInputFiles('input[type=file]', resolve(photo));
		await page.waitForFunction(() => /Done!|Error:/.test(document.body.innerText), null, { timeout: 120000 });
		const block = page.locator('[data-state="confirmed"][data-printing-state="unknown"]').filter({ hasText: 'Giant Growth' });
		assert(await block.count() === 1, 'identity is confirmed while its printing is still open');
		assert(await block.locator('.ring-1').count() === 0, 'no printing appears selected before a choice');
		assert(await block.getByRole('button', { name: 'Add', exact: true }).count() === 0, 'unresolved printing has no Add action');
		assert(await block.locator('.opacity-40').count() === 0, 'unresolved alternatives are equally visible');
		await page.getByRole('button', { name: /Copy for Moxfield/ }).click();
		assert((await page.evaluate(() => window.copiedScanText)).trim().split('\n').length === 2, 'export omits both unresolved printings');
		const choose = block.getByRole('button', { name: 'Select printing', exact: true }).nth(1);
		await choose.focus(); await page.keyboard.press('Enter');
		const selected = page.locator('[data-state="confirmed"][data-printing-state="confirmed"]').filter({ hasText: 'Giant Growth' });
		assert(await selected.locator('.ring-1').count() === 1, 'an explicit keyboard choice establishes one printing');
		await page.getByRole('button', { name: /Copy for Moxfield/ }).click();
		const copied = await page.evaluate(() => window.copiedScanText);
		assert(copied.trim().split('\n').length === 3 && copied.includes('Giant Growth'), 'export includes the explicitly chosen printing');
		if (loggedIn) {
			assert(await selected.getByRole('button', { name: 'Add', exact: true }).count() === 1, 'signed-in user can add only the selected printing');
			await page.getByRole('button', { name: /Select all/ }).click();
			assert(await page.getByRole('button', { name: 'Import 3 selected', exact: true }).count() === 1, 'bulk selection includes only three established printings');
			await selected.getByRole('button', { name: 'Add', exact: true }).click();
			await selected.getByText('Added!', { exact: true }).waitFor();
			assert(writes.length === 1, 'only the explicit Add generates a collection request');
		} else assert(await selected.getByRole('button', { name: 'Add', exact: true }).count() === 0, 'guest can choose a printing without a collection action');
		assert(errors.length === 0, 'printing selection has no browser errors');
		await context.close();
	}
	console.log(`PASS ${assertions} printing UI assertions`);
} finally { await browser.close(); }
